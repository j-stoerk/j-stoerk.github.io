"""Simplify the site's public-domain Natural Earth land into schematic outlines.

Run manually with Python. No extra packages or network requests are required.
"""
from pathlib import Path
import json, math

ROOT = Path(__file__).resolve().parent.parent

def simplify(points, tolerance=.48):
    if len(points)<3: return points
    a,b=points[0],points[-1]
    dx,dy=b[0]-a[0],b[1]-a[1]
    length=math.hypot(dx,dy)
    def distance(p):
        return abs(dy*p[0]-dx*p[1]+b[0]*a[1]-b[1]*a[0])/length if length else math.hypot(p[0]-a[0],p[1]-a[1])
    index=max(range(1,len(points)-1),key=lambda i:distance(points[i]))
    if distance(points[index])<=tolerance: return [a,b]
    return simplify(points[:index+1],tolerance)[:-1]+simplify(points[index:],tolerance)

data=json.loads((ROOT/'_src/media/battery-world-land.json').read_text())
lines=[]
for feature in data['features']:
    geometry=feature['geometry']
    polygons=[geometry['coordinates']] if geometry['type']=='Polygon' else geometry['coordinates']
    for polygon in polygons:
        for ring in polygon:
            if max(p[0] for p in ring)-min(p[0] for p in ring)<3 and max(p[1] for p in ring)-min(p[1] for p in ring)<3: continue
            line=[[round(lon,2),round(lat,2)] for lon,lat in simplify(ring)]
            if len(line)>3:lines.append(line)
target=ROOT/'earth-coastlines.js'
target.write_text('/* Natural Earth land outlines; public domain. Generated by _src/generate-earth-coastlines.py. */\nwindow.PortfolioCoastlines='+json.dumps(lines,separators=(',',':'))+';\n',encoding='utf8')
print(f'{len(lines)} outlines; {sum(map(len,lines))} vertices; {target.stat().st_size} bytes')
